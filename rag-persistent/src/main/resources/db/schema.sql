CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

CREATE TABLE IF NOT EXISTS public.kb_chunk (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    knowledge_base_id bigint NOT NULL,
    document_id bigint NOT NULL,
    document_version integer NOT NULL DEFAULT 1,
    chunk_no integer NOT NULL,
    title text,
    content text NOT NULL,
    content_hash varchar(64) NOT NULL,
    token_count integer,
    source_uri text,
    source_locator jsonb NOT NULL DEFAULT '{}'::jsonb,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    embedding_profile varchar(128) NOT NULL,
    embedding_model varchar(128) NOT NULL,
    embedding public.vector,
    embedded_at timestamptz(6),
    status varchar(16) NOT NULL DEFAULT 'pending',
    error_message text,
    created_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at timestamptz(6),
    CONSTRAINT uk_kb_chunk_version UNIQUE
        (tenant_id, knowledge_base_id, document_id, document_version, embedding_profile, chunk_no),
    CONSTRAINT ck_kb_chunk_position CHECK (document_version > 0 AND chunk_no >= 0),
    CONSTRAINT ck_kb_chunk_content CHECK (btrim(content) <> ''),
    CONSTRAINT ck_kb_chunk_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_kb_chunk_json CHECK
        (jsonb_typeof(source_locator) = 'object' AND jsonb_typeof(metadata) = 'object'),
    CONSTRAINT ck_kb_chunk_vector CHECK (embedding IS NULL OR public.vector_norm(embedding) > 0),
    CONSTRAINT ck_kb_chunk_ready CHECK
        (status <> 'ready' OR (embedding IS NOT NULL AND embedded_at IS NOT NULL)),
    CONSTRAINT ck_kb_chunk_token_count CHECK (token_count IS NULL OR token_count > 0),
    CONSTRAINT ck_kb_chunk_status CHECK (status IN ('pending', 'ready', 'failed', 'archived'))
);

CREATE INDEX IF NOT EXISTS idx_kb_chunk_search_scope
    ON public.kb_chunk (tenant_id, knowledge_base_id, embedding_profile)
    WHERE status = 'ready' AND deleted_at IS NULL;

COMMENT ON TABLE public.kb_chunk IS '知识库片段表；一行对应一个文档入库版本、片段位置和向量配置';
COMMENT ON COLUMN public.kb_chunk.id IS '片段行主键，数据库自动生成';
COMMENT ON COLUMN public.kb_chunk.tenant_id IS '所属租户业务ID；单租户系统可使用固定值';
COMMENT ON COLUMN public.kb_chunk.knowledge_base_id IS '所属知识库业务ID，用于限定检索范围';
COMMENT ON COLUMN public.kb_chunk.document_id IS '来源文档的稳定业务ID；文档更新后保持不变';
COMMENT ON COLUMN public.kb_chunk.document_version IS '文档入库修订号，从1开始；原文、解析或分块规则变化时递增';
COMMENT ON COLUMN public.kb_chunk.chunk_no IS '当前文档入库版本内的片段顺序，从0开始，可用于查找相邻片段';
COMMENT ON COLUMN public.kb_chunk.title IS '片段标题或所属章节标题，可为空';
COMMENT ON COLUMN public.kb_chunk.content IS '用于向量化和提供给大模型的片段正文，建议保留必要的章节标题';
COMMENT ON COLUMN public.kb_chunk.content_hash IS 'content按UTF-8编码计算的SHA-256，小写64位十六进制字符串，由应用生成';
COMMENT ON COLUMN public.kb_chunk.token_count IS '使用对应模型分词器统计的片段Token数量，未统计时为空';
COMMENT ON COLUMN public.kb_chunk.source_uri IS '来源文档地址，例如本地文件路径、对象存储地址或网页URL';
COMMENT ON COLUMN public.kb_chunk.source_locator IS '原文定位信息，例如section_path、page、line_start和line_end';
COMMENT ON COLUMN public.kb_chunk.metadata IS '业务扩展属性，例如标签、业务分类、语言等，必须为JSON对象';
COMMENT ON COLUMN public.kb_chunk.embedding_profile IS '不可变向量配置标识，区分实际模型版本、向量维度及预处理规则；配置变化时使用新标识';
COMMENT ON COLUMN public.kb_chunk.embedding_model IS '生成向量时使用的模型名称，例如Qwen3.5';
COMMENT ON COLUMN public.kb_chunk.embedding IS '默认2560维单精度浮点向量，处理中可为空；查询向量须使用相同向量配置';
COMMENT ON COLUMN public.kb_chunk.embedded_at IS '当前片段成功生成向量的时间，ready状态必须有值';
COMMENT ON COLUMN public.kb_chunk.status IS '片段状态：pending处理中，ready已发布可检索，failed处理失败，archived历史版本已归档';
COMMENT ON COLUMN public.kb_chunk.error_message IS '最近一次处理失败的原因，成功后清空';
COMMENT ON COLUMN public.kb_chunk.created_at IS '片段行创建时间';
COMMENT ON COLUMN public.kb_chunk.updated_at IS '片段行最后更新时间；插入时使用默认值，后续更新由触发器维护';
COMMENT ON COLUMN public.kb_chunk.deleted_at IS '逻辑删除时间；为空表示未删除，非空表示已删除并退出检索';
COMMENT ON INDEX public.idx_kb_chunk_search_scope IS '限定租户、知识库及向量配置，仅包含已发布且未删除的片段';
