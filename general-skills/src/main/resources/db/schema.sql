CREATE TABLE public.personal_skill
(
    -- 主键
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 数据归属，由服务端根据当前登录身份设置
    tenant_id       bigint        NOT NULL,
    owner_user_id   bigint        NOT NULL,

    -- 技能标识，例如 spring-code-review
    name            varchar(64)   NOT NULL,

    -- 面向模型的描述：技能的用途和适用场景
    description     varchar(1024) NOT NULL,

    -- SKILL.md 的 Markdown 正文，不包含 YAML 头部
    instructions_md text          NOT NULL,

    -- YAML 头部的其他属性，不重复存储 name、description
    extra_frontmatter jsonb NOT NULL DEFAULT '{}'::jsonb,

    -- draft：草稿；enabled：启用；disabled：停用
    status          varchar(16)   NOT NULL DEFAULT 'draft',

    -- 乐观锁版本号，每次修改递增，不表示保留历史版本
    revision        bigint        NOT NULL DEFAULT 1,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 同一租户、同一用户下，技能名称唯一
    CONSTRAINT uq_personal_skill_name
        UNIQUE (tenant_id, owner_user_id, name),

    -- 名称由小写英文字母、数字和单个连字符组成
    CONSTRAINT ck_personal_skill_name
        CHECK (name ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
) ,

    -- 描述与正文不能为空白
    CONSTRAINT ck_personal_skill_content
        CHECK (
            btrim(description) <> ''
            AND btrim(instructions_md) <> ''
        ),

    -- 扩展头部必须为 JSON 对象，且不能包含已独立存储的字段
    CONSTRAINT ck_personal_skill_frontmatter
        CHECK (
            jsonb_typeof(extra_frontmatter) = 'object'
            AND NOT (
                extra_frontmatter ?| ARRAY['name', 'description']
            )
        ),

    CONSTRAINT ck_personal_skill_status
        CHECK (status IN ('draft', 'enabled', 'disabled')),

    CONSTRAINT ck_personal_skill_revision
        CHECK (revision > 0)
);

-- 查询当前用户已启用的技能
CREATE INDEX idx_personal_skill_enabled
    ON public.personal_skill (tenant_id, owner_user_id) WHERE status = 'enabled';

COMMENT ON TABLE public.personal_skill
    IS '个人技能定义表，一行表示一个租户下某个用户拥有的一份技能';